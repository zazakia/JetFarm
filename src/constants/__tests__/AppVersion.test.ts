import * as fs from 'fs';
import * as path from 'path';
import { mySchema } from '../../database/schema';
import {
    APP_VERSION,
    APP_BUILD_NUMBER,
    APP_RELEASE_NAME,
    APP_DOWNLOAD_URL,
    APP_VERSIONED_DOWNLOAD_URL,
    PRIMARY_VERSION_URL,
    FALLBACK_VERSION_URL,
    PRODUCTION_APP_URL,
    PUBLIC_APP_URL,
    resolvePublicAppUrl,
    WATERMELONDB_SCHEMA_VERSION,
    getAppVersion,
    getReleaseName,
    getFullReleaseString,
    getAppFooterText,
} from '../AppVersion';

// The self-hosted Hetzner vhost serves the app but publishes neither `/download` nor a
// current `version.json` (all three download paths return 404 and its manifest is frozen
// at 0.1.1), so it must not be the default origin for release URLs.
const BROKEN_DOWNLOAD_HOST = 'jetfarm.818.quest';
const CANONICAL_APP_URL = 'https://jetfarm.pages.dev';

describe('AppVersion constants and utilities', () => {
    it('exports valid semantic version and build number', () => {
        expect(APP_VERSION).toMatch(/^\d+\.\d+\.\d+$/);
        expect(typeof APP_BUILD_NUMBER).toBe('number');
        expect(APP_BUILD_NUMBER).toBeGreaterThanOrEqual(1);
    });

    it('never points a shipped release URL at the download-less Hetzner host', () => {
        [
            APP_DOWNLOAD_URL,
            APP_VERSIONED_DOWNLOAD_URL,
            PRIMARY_VERSION_URL,
            FALLBACK_VERSION_URL,
        ].forEach((url) => {
            expect(url).not.toContain(BROKEN_DOWNLOAD_HOST);
        });
    });

    it('defaults to the canonical Cloudflare Pages origin', () => {
        expect(PRODUCTION_APP_URL).toBe(CANONICAL_APP_URL);
        expect(resolvePublicAppUrl('', '')).toBe(CANONICAL_APP_URL);
    });

    it('resolves the public origin from config, then the web origin, then the live default', () => {
        expect(resolvePublicAppUrl('https://jetfarm.pages.dev/', undefined)).toBe(
            'https://jetfarm.pages.dev'
        );
        expect(resolvePublicAppUrl('', 'https://preview.example.dev')).toBe(
            'https://preview.example.dev'
        );
        expect(resolvePublicAppUrl('', '')).toBe(PRODUCTION_APP_URL);
    });

    it('ignores unusable web origins such as "null" and file://', () => {
        expect(resolvePublicAppUrl('', 'null')).toBe(PRODUCTION_APP_URL);
        expect(resolvePublicAppUrl('', 'file:///tmp/index.html')).toBe(PRODUCTION_APP_URL);
    });

    it('derives every release URL from one resolved origin', () => {
        expect(PUBLIC_APP_URL).toBe(resolvePublicAppUrl());
        expect(APP_DOWNLOAD_URL).toBe(`${PUBLIC_APP_URL}/download`);
        expect(APP_VERSIONED_DOWNLOAD_URL).toBe(`${PUBLIC_APP_URL}/download/v${APP_VERSION}`);
        expect(PRIMARY_VERSION_URL).toBe(`${PUBLIC_APP_URL}/version.json`);
    });

    it('keeps the release tooling on the canonical origin so a deploy cannot revert it', () => {
        // AppVersion.ts is generated by sync-version.mjs on every deploy, and
        // deploy-cloudflare.mjs writes the apkUrl fields of version.json. Fixing only
        // the hand-written file would have been overwritten by the next release.
        [
            'scripts/sync-version.mjs',
            'scripts/deploy-cloudflare.mjs',
            'scripts/prepare-cloudflare-dist.mjs',
            'scripts/lib/writeDistVersionLib.js',
        ].forEach((relPath) => {
            const source = fs.readFileSync(path.join(process.cwd(), relPath), 'utf8');

            expect(source).not.toContain(`'${BROKEN_DOWNLOAD_HOST}'`);
            expect(source).toContain('jetfarm.pages.dev');
        });

        expect(fs.readFileSync(path.join(process.cwd(), 'scripts/sync-version.mjs'), 'utf8')).toContain(
            'resolvePublicAppUrl'
        );
    });

    it('falls back to a genuinely independent origin so the retry has redundancy', () => {
        // AppUpdateService loops [PRIMARY, FALLBACK]; identical values made the
        // second attempt re-request the same host and recover nothing.
        expect(FALLBACK_VERSION_URL).not.toBe(PRIMARY_VERSION_URL);
        expect(FALLBACK_VERSION_URL).toBe(
            `${process.env.EXPO_PUBLIC_SUPABASE_URL}/storage/v1/object/public/downloads/version.json`
        );
    });

    it('tracks the real WatermelonDB schema version instead of a frozen literal', () => {
        const schema = fs.readFileSync(
            path.join(process.cwd(), 'src', 'database', 'schema.ts'),
            'utf8'
        );
        const declared = schema.match(/appSchema\(\{\s*version:\s*(\d+)/);

        expect(declared).not.toBeNull();
        const schemaVersion = Number(declared?.[1]);
        expect(Number.isInteger(schemaVersion)).toBe(true);
        expect(schemaVersion).toBeGreaterThan(0);

        // The exported constant is regenerated from schema.ts by scripts/sync-version.mjs on every
        // release; both the parsed source literal and the runtime appSchema object must agree, so
        // bumping src/database/schema.ts without re-syncing AppVersion.ts breaks this test.
        expect(mySchema.version).toBe(schemaVersion);
        expect(WATERMELONDB_SCHEMA_VERSION).toBe(schemaVersion);
    });

    it('formats release names and full release strings correctly', () => {
        expect(getReleaseName()).toBe(`v${getAppVersion()}`);
        expect(getFullReleaseString()).toContain(`v${getAppVersion()}`);
        expect(getFullReleaseString()).toContain(`Build ${APP_BUILD_NUMBER}`);
    });

    it('returns the Agri-One footer text with branding and version', () => {
        const footer = getAppFooterText();
        expect(footer).toContain('Agri-One');
        expect(footer).not.toContain('JetFarm');
        expect(footer).toContain(`v${getAppVersion()}`);
        expect(footer).toContain(`Build ${APP_BUILD_NUMBER}`);
    });
});
